CREATE TABLE IF NOT EXISTS public.dre_folha (
  id          serial PRIMARY KEY,
  tipo        varchar(10)  NOT NULL,
  nome        varchar(120),
  funcao      varchar(80)  NOT NULL,
  divisao     varchar(40)  NOT NULL,
  admissao    date,
  salario     numeric      NOT NULL,
  custo_total numeric      NOT NULL,
  is_vaga     boolean      NOT NULL DEFAULT false,
  criado_em   timestamptz  DEFAULT now()
);

ALTER TABLE public.dre_folha ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "dre_folha_read" ON public.dre_folha;
CREATE POLICY "dre_folha_read" ON public.dre_folha FOR SELECT TO authenticated, anon USING (true);
DROP POLICY IF EXISTS "dre_folha_manage" ON public.dre_folha;
CREATE POLICY "dre_folha_manage" ON public.dre_folha FOR ALL TO service_role USING (true) WITH CHECK (true);

