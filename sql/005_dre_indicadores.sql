CREATE TABLE IF NOT EXISTS public.dre_indicadores (
  id        serial PRIMARY KEY,
  mes_ano   varchar(7)  NOT NULL,
  tipo      varchar(20) NOT NULL CHECK (tipo IN ('orcado', 'realizado')),
  indicador varchar(40) NOT NULL,
  valor     numeric,
  criado_em timestamptz DEFAULT now(),
  UNIQUE (mes_ano, tipo, indicador)
);

ALTER TABLE public.dre_indicadores ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "dre_indicadores_read" ON public.dre_indicadores;
CREATE POLICY "dre_indicadores_read" ON public.dre_indicadores FOR SELECT TO authenticated, anon USING (true);
DROP POLICY IF EXISTS "dre_indicadores_manage" ON public.dre_indicadores;
CREATE POLICY "dre_indicadores_manage" ON public.dre_indicadores FOR ALL TO service_role USING (true) WITH CHECK (true);

